"""Generate frontend/src/data/letterShapes.ts - the ASL alphabet reference
chart's hand constructions. Not a copied/licensed chart image: each letter
is built from real ASL letterform geometry using the same CANON/fold/
thumb_to/splay helpers selftest.py uses for its synthetic test hands, in
the exact 21-point topology the app's own landmark overlay uses.

    python tools/gen_letter_shapes.py

Re-run this if skeleton.py's landmark topology or CANON ever changes.

Honesty note: several constructions here do NOT currently agree with
fingerspell.classify_letter() - this script prints which ones. That's not
a bug in this script; it's real evidence of gaps in the rule-based
classifier's scoring beyond the ones already fixed this session:

  - S structurally dominates T in the point-scoring formula: T's score
    (max 0.8) can only win in exactly the handshape zone where S's own
    condition (thumb_across) is ALSO true and scores higher (max 0.95) -
    so T is effectively unreachable for any genuinely fisted hand, not
    just hard to hit.
  - O's "thumb among fingers + touching everything" condition is greedy
    and catches several otherwise-reasonable fist-family thumb positions
    meant for A/M/N/E.

This is exactly the kind of fixed-priority-weight problem a trained
classifier (tools/train_fingerspell.py) sidesteps by construction - it
doesn't have hand-coded letter priorities to get wrong. The reference
chart intentionally shows correct ASL letterforms regardless, since its
job is to teach the user real ASL, not to mirror today's classifier.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from fingerspell import classify_letter
from selftest import CANON, fold, place, splay, thumb_to

FRONTEND_OUT = (Path(__file__).resolve().parent.parent
                / "frontend" / "src" / "data" / "letterShapes.ts")

# letters that share a base handshape with another, distinguished only by
# hand orientation - rendered rotated (clockwise degrees) in the frontend.
ROTATION = {"G": -90, "H": -90, "Q": 180, "P": 180}
MOTION = {"J": "draw a J", "Z": "draw a Z"}


def build() -> dict[str, "list[list[float]]"]:
    fisted = fold(CANON, ["index", "middle", "ring", "pinky"])
    hands = {
        "A": thumb_to(fisted, (-0.26, -0.02)),
        "S": thumb_to(fisted, (-0.20, 0.05)),
        "T": thumb_to(fisted, (-0.06, -0.05)),
        "M": thumb_to(fisted, (-0.04, -0.08)),
        "N": thumb_to(fisted, (-0.05, -0.04)),
        "E": thumb_to(fisted, (-0.04, 0.00)),
        "B": thumb_to(CANON, (0.0, 0.08)),
        "C": thumb_to(fold(CANON, ["index", "middle", "ring", "pinky"], 0.5), (-0.35, 0.05)),
        "O": thumb_to(fold(CANON, ["index", "middle", "ring", "pinky"], 0.62), (-0.06, -0.22)),
        "I": fold(CANON, ["index", "middle", "ring"]),
        "Y": thumb_to(fold(CANON, ["index", "middle", "ring"]), (-0.30, 0.06)),
        "L": thumb_to(fold(CANON, ["middle", "ring", "pinky"]), (-0.32, 0.12)),
        "D": thumb_to(fold(CANON, ["middle", "ring", "pinky"]), (0.0, -0.02)),
        "X": fold(CANON, ["index"], 0.5),
        "U": fold(CANON, ["ring", "pinky"]),
        "V": splay(fold(CANON, ["ring", "pinky"]), 0.13),
        "K": thumb_to(fold(CANON, ["ring", "pinky"]), (-0.15, -0.45)),
        "W": fold(CANON, ["pinky"]),
        "F": thumb_to(fold(CANON, ["index"], 0.75), (-0.07, 0.0)),
    }

    r_base = fold(CANON, ["ring", "pinky"]).copy()
    r_base[[6, 7, 8]], r_base[[10, 11, 12]] = r_base[[10, 11, 12]].copy(), r_base[[6, 7, 8]].copy()
    hands["R"] = r_base

    hands["G"] = hands["D"]
    hands["Q"] = hands["D"]
    hands["H"] = hands["U"]
    hands["P"] = hands["K"]
    hands["J"] = hands["I"]
    hands["Z"] = hands["D"]

    out: dict[str, list[list[float]]] = {}
    for letter in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        placed = place(hands[letter])
        got = classify_letter(placed, "Right")
        flag = "" if got.letter == letter else f"  (classify_letter currently says {got.letter})"
        print(f"{letter}: {'OK' if not flag else 'constructed from ASL geometry' + flag}")
        out[letter] = [[round(float(x), 4), round(float(y), 4)] for x, y in placed[:, :2]]
    return out


def write_ts(shapes: dict[str, "list[list[float]]"]) -> None:
    lines = [
        "// Generated by tools/gen_letter_shapes.py from the app's own 21-point",
        "// hand skeleton, constructed from real ASL letterform geometry (not a",
        "// copied/licensed chart image) - see that script's docstring for the",
        "// honest list of where this currently disagrees with classify_letter().",
        "",
        "export type HandPoints = [number, number][];",
        "",
        "export const LETTER_SHAPES: Record<string, HandPoints> = {",
    ]
    for letter in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        pts = ", ".join(f"[{x},{y}]" for x, y in shapes[letter])
        lines.append(f"  {letter}: [{pts}],")
    lines += [
        "};",
        "",
        "// Letters that share a handshape with another, distinguished only by hand",
        "// orientation - rendered rotated (degrees, clockwise) from the base shape.",
        "export const LETTER_ROTATION: Record<string, number> = {",
        "  " + ", ".join(f"{k}: {v}" for k, v in ROTATION.items()) + ",",
        "};",
        "",
        "// Air-drawn letters - shown as their static base handshape + a motion hint.",
        "export const MOTION_LETTERS: Record<string, string> = {",
        "  " + ", ".join(f'{k}: "{v}"' for k, v in MOTION.items()) + ",",
        "};",
        "",
    ]
    FRONTEND_OUT.parent.mkdir(parents=True, exist_ok=True)
    FRONTEND_OUT.write_text("\n".join(lines))
    print(f"\nwrote {FRONTEND_OUT}")


if __name__ == "__main__":
    write_ts(build())
